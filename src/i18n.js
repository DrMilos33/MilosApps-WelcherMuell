export function normalizeLanguage(value) {
  return value === "en" ? "en" : "de";
}

export function translate(language, key, values = {}) {
  const selected = normalizeLanguage(language);
  const template = UI_MESSAGES[selected][key] ?? UI_MESSAGES.de[key] ?? key;
  return String(template).replace(/\{\{(\w+)\}\}/g, (_, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : `{{${name}}}`
  );
}

function localizeItem(item, translations) {
  const translation = translations[item.id];
  return {
    ...item,
    ...translation,
    route: {
      ...item.route,
      ...translation.route
    },
    warning: item.warning ? translation.warning : null
  };
}

function localizeSource(source, translations) {
  return {
    ...source,
    ...translations[source.id]
  };
}

function localizeRegion(region, translations) {
  const translation = translations[region.id];
  const routeOverrides = Object.fromEntries(
    Object.entries(region.routeOverrides ?? {}).map(([routeType, override]) => [
      routeType,
      {
        ...override,
        ...(translation.routeOverrides?.[routeType] ?? {})
      }
    ])
  );
  return {
    ...region,
    ...translation,
    routeOverrides
  };
}

export function localizeCatalogs(
  { itemsCatalog, sourcesCatalog, regionsCatalog, localeCatalog },
  language
) {
  const selected = normalizeLanguage(language);
  if (selected === "de") {
    return {
      items: itemsCatalog.items,
      sources: sourcesCatalog.sources,
      regions: regionsCatalog.regions,
      sourcesEditorialUse: sourcesCatalog.editorialUse
    };
  }

  return {
    items: itemsCatalog.items.map((item) =>
      localizeItem(item, localeCatalog.items)
    ),
    sources: sourcesCatalog.sources.map((source) =>
      localizeSource(source, localeCatalog.sources)
    ),
    regions: regionsCatalog.regions.map((region) =>
      localizeRegion(region, localeCatalog.regions)
    ),
    sourcesEditorialUse: localeCatalog.editorialUse
  };
}
